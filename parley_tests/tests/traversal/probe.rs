//! Probes that establish what the rest of the harness is allowed to assume.
//!
//! # The font-sensitivity question
//!
//! Reading `parley/src/layout/data.rs` suggests `ClusterData::text_len` is `char::len_utf8()` of a
//! single source char, unconditionally — shaping picks glyphs and advances, but does not decide how
//! many bytes a cluster spans. If true, cursor motion and deletion measure the same whether or not
//! a font covers the script, and the harness needs no Devanagari/Thai/Hangul/CJK font assets.
//!
//! That is a claim about behavior, so it is measured rather than believed:
//! [`traversal_cluster_ranges_are_font_invariant`] compares a tier that shapes Arabic against one
//! that does not, and [`traversal_clusters_tile_the_text`] checks the one-cluster-per-char claim
//! across the whole corpus. **These gate all font work**: only a `text_range` that actually moves
//! could justify vendoring font assets.
//!
//! # The trap this module also pins
//!
//! A layout with no resolvable font has zero clusters, and every traversal API then falls back to a
//! whole-text index — so a test written against it passes for *any* input. That is not
//! hypothetical: see [`traversal_cursor_test_helper_produces_clusters`].

use std::fmt::Write;

use crate::test_name;
use crate::util::TestEnv;

